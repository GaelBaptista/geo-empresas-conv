/** Índice slug → centro do bairro */
export function fortalezaBairroIndex(): Map<string, BairroCenter> {
  const map = new Map<string, BairroCenter>();
  for (const b of FORTALEZA_BAIRRO_CENTERS) {
    const slug = b.name
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_|_$/g, '');
    if (!map.has(slug)) map.set(slug, b);
  }
  return map;
}
